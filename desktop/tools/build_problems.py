def node(move, comment="", reply=None, reply_comment="", next_=None, wrong=None):
    n = {"move": move, "comment": comment}
    if reply:
        n["reply"] = reply
        n["reply_comment"] = reply_comment
    if next_:
        n["next"] = next_
    if wrong:
        n["wrong"] = wrong
    return n


def wrong(move, comment, reply=None):
    w = {"move": move, "comment": comment}
    if reply:
        w["reply"] = reply
    return w


def ladder_line(rows, target, attacker=BLACK, first=None):
    """Строит вариант лестницы автоматически: атакующий ставит атари, защитник вытягивает камни."""
    b = Board.from_ascii(rows)
    t = from_gtp(target, 9)
    line = []
    color = attacker
    while b.get(t) == other(attacker):
        stones, libs = b.group(t)
        if color == attacker:
            if len(libs) == 1:
                mv = next(iter(libs))
            else:
                mv = None
                cands = sorted(libs) if not (first and not line) else [from_gtp(first, 9)]
                for l in cands:
                    bb = b.copy()
                    bb.play(attacker, l)
                    if capture_search(bb, t, attacker, False):
                        mv = l
                        break
                assert mv is not None, "лестница не работает"
        else:
            mv = next(iter(libs))
        b.play(color, mv)
        line.append(to_gtp(mv, 9))
        color = other(color)
    return line


def ladder_tree(b, t, attacker, final_comment, step_comment, depth=0):
    """Дерево лестницы: принимаются все атари, после которых камень не убегает."""
    stones, libs = b.group(t)
    nodes = []
    for l in sorted(libs):
        bb = b.copy()
        bb.play(attacker, l)
        if bb.get(t) != other(attacker):
            nodes.append(node(to_gtp(l, 9), final_comment))
            continue
        if not capture_search(bb, t, attacker, False):
            continue
        _, dlibs = bb.group(t)
        reply = next(iter(dlibs))
        try:
            bb.play(other(attacker), reply)
        except Exception:  # белым некуда вытягиваться — камни уже пойманы
            nodes.append(node(to_gtp(l, 9), "Белые в атари, а вытянуть камни некуда: это был бы ход-самоубийство. "
                                            "Камни пойманы, следующим ходом их можно снять. Лестница сработала!"))
            continue
        sub = ladder_tree(bb, t, attacker, final_comment, "Правильно, снова атари.", depth + 1)
        nodes.append(node(to_gtp(l, 9), step_comment, to_gtp(reply, 9), "", sub))
    return nodes


def linear(moves, comments, final_comment):
    """Вариант из чередующихся ходов: [наш, ответ, наш, ответ, ..., наш]."""
    nodes = None
    pairs = []
    for i in range(0, len(moves), 2):
        pairs.append((moves[i], moves[i + 1] if i + 1 < len(moves) else None))
    for idx in range(len(pairs) - 1, -1, -1):
        mv, rp = pairs[idx]
        c = final_comment if idx == len(pairs) - 1 else comments.get(idx, "Правильно, продолжайте.")
        nodes = [node(mv, c, rp, "", nodes)]
    return {"next": nodes}


