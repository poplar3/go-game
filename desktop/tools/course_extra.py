def node(move, comment="", reply=None, reply_comment="", next_=None, wrong=None):
    n = {"move": move, "comment": comment}
    if reply:
        n["reply"] = reply
        n["reply_comment"] = reply_comment
    if next_:
        n["next"] = next_
    if wrong:
        n["wrong"] = wrong
    return n


def wrong(move, comment, reply=None):
    w = {"move": move, "comment": comment}
    if reply:
        w["reply"] = reply
    return w


def board19(stones: dict[str, str]) -> list[str]:
    """Пустая доска 19×19 с камнями {"Q16": "X", ...}."""
    letters = "ABCDEFGHJKLMNOPQRST"
    g = [list(E19) for _ in range(19)]
    for p, c in stones.items():
        g[19 - int(p[1:])][letters.index(p[0])] = c
    return ["".join(r) for r in g]


